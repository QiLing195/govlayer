"""各数据集的评测查询集（**单一来源**）。

为什么集中放、并且强制校验：
  查询集是全部检索结论的**唯一依据**，而这个会话里它已经出过两次事故：
    1. 「措辞远离」组里混进了目标关键词（"扣"），悄悄抬高了关键词检索的基线成绩；
    2. 换了数据集却仍用旧数据集的查询集算分数——脚本**照样打印一个"建议阈值"**，
       而那个数字会被写进代码常数。
  所以：每个数据集的每组查询都有配套的期望目标 id，并由
  `tests/test_eval_query_sets.py` 对**每个数据集**自动校验：
    · 贴近组必须至少含一个目标关键词（否则不配叫"贴近"）；
    · 远离组不得含任何目标关键词（否则不配叫"远离"）；
    · 无关组不得含**任何**条款的关键词（否则它不是"无关"）；
    · 期望目标必须真实存在，且必须有最低级别可见内容。

四层查询的分工：
  near     —— 措辞贴近（含关键词）：对照组，关键词检索本应表现良好
  distant  —— 措辞远离（避开关键词）：**真正决定语义检索价值的一组**
  off_domain            —— 完全跑题：测阈值的"绝对下限"
  same_domain_uncovered —— 本制度领域内但确实没规定：测"相似度 ≠ 覆盖"的严重程度

⚠️ 最后两档**必须分开统计**，混在一起会把最重要的发现藏起来（详见 sets_for 的说明）。
"""

