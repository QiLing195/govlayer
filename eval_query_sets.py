DATASETS: tuple[str, ...] = tuple(NEAR_QUERIES)


def sets_for(dataset_id: str) -> tuple[
        list[tuple[str, str]], list[tuple[str, str]], list[str], list[str]] | None:
    """返回 (near, distant, off_domain, same_domain_uncovered)。

    该数据集没有配套查询集时返回 None——调用方**必须硬失败**，不能"尽力而为"：
    否则会拿 A 库的问题去给 B 库标定阈值，打印出一个看起来很正常、
    却毫无意义的数字（而这个数字通常会被写进代码常数）。

    ⚠️ 两档无关问题**必须分开统计**。混在一起会得出错误结论：
    实测混着看只能说"两个分布分不开"，分开看才发现远域组与相关组几乎完美可分，
    而同域组深埋在相关组内部——**两者对应完全不同的产品结论**。
    """
    if dataset_id not in NEAR_QUERIES:
        return None
    return (NEAR_QUERIES[dataset_id], DISTANT_QUERIES[dataset_id],
            OFF_DOMAIN_QUERIES.get(dataset_id, []),
            SAME_DOMAIN_UNCOVERED_QUERIES.get(dataset_id, []))
